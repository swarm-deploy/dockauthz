// Command generate produces exhaustive, typed equality without runtime reflection.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"os"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

type generator struct {
	imports map[string]string
	names   map[types.Type]string
	body    bytes.Buffer
	shapes  map[*types.Named]bool
}

func main() {
	pkgs, err := packages.Load(
		&packages.Config{
			Mode: packages.NeedName |
				packages.NeedTypes |
				packages.NeedImports |
				packages.NeedDeps,
		},
		"github.com/moby/moby/api/types/swarm",
	)
	if err != nil || packages.PrintErrors(pkgs) > 0 {
		panic("cannot load Docker types")
	}
	g := &generator{imports: map[string]string{}, names: map[types.Type]string{}, shapes: map[*types.Named]bool{}}
	root := pkgs[0].Types.Scope().Lookup("ServiceSpec").Type()
	name := g.equal(root)
	var source bytes.Buffer
	source.WriteString("// Code generated by go generate; DO NOT EDIT.\npackage mutation\nimport (\n")
	var paths []string
	for path := range g.imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&source, "%s %q\n", g.imports[path], path)
	}
	source.WriteString(")\n")
	source.Write(g.body.Bytes())
	fmt.Fprintf(&source, "func equalSpec(a,b swarm.ServiceSpec) bool { return %s(a,b) }\n", name)
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		panic(err)
	}
	if writeErr := os.WriteFile("equal_generated.go", formatted, 0600); writeErr != nil {
		panic(writeErr)
	}
}

func (g *generator) typeName(t types.Type) string {
	return types.TypeString(t, func(p *types.Package) string {
		if name, ok := g.imports[p.Path()]; ok {
			return name
		}
		name := p.Name()
		for _, existing := range g.imports {
			if existing == name {
				name += fmt.Sprint(len(g.imports))
			}
		}
		g.imports[p.Path()] = name
		return name
	})
}

func (g *generator) equal(t types.Type) string {
	t = types.Unalias(t)
	if name, ok := g.names[t]; ok {
		return name
	}
	name := fmt.Sprintf("equal%d", len(g.names))
	g.names[t] = name
	var b strings.Builder
	fmt.Fprintf(&b, "func %s(a,b %s) bool {\n", name, g.typeName(t))
	// netip values have private internals and documented value equality.
	if n, ok := t.(*types.Named); ok && n.Obj().Pkg().Path() == "net/netip" {
		b.WriteString("return a == b\n}\n")
		g.body.WriteString(b.String())
		return name
	}
	switch u := t.Underlying().(type) {
	case *types.Basic:
		b.WriteString("return a == b\n")
	case *types.Pointer:
		fmt.Fprintf(&b, "if a == nil || b == nil { return a == b }; return %s(*a,*b)\n", g.equal(u.Elem()))
	case *types.Slice:
		fmt.Fprintf(
			&b,
			"if (a == nil) != (b == nil) || len(a) != len(b) { return false }; "+
				"for i := range a { if !%s(a[i], b[i]) { return false } }; return true\n",
			g.equal(u.Elem()),
		)
	case *types.Map:
		fmt.Fprintf(
			&b,
			"if (a == nil) != (b == nil) || len(a) != len(b) { return false }; "+
				"for k,v := range a { other,ok := b[k]; "+
				"if !ok || !%s(v,other) { return false } }; return true\n",
			g.equal(u.Elem()),
		)
	case *types.Array:
		fmt.Fprintf(&b, "for i := range a { if !%s(a[i],b[i]) { return false } }; return true\n", g.equal(u.Elem()))
	case *types.Struct:
		if n, ok := t.(*types.Named); ok && !g.shapes[n] {
			g.shapes[n] = true
			// Conversion is a compile-time schema guard. Added/removed fields or
			// changed field types force regeneration and security review.
			fmt.Fprintf(&g.body, "var _ = (%s)(%s{})\n", g.shape(u), g.typeName(n))
		}
		for i := 0; i < u.NumFields(); i++ {
			f := u.Field(i)
			if !f.Exported() {
				panic("unreviewed private field in " + g.typeName(t))
			}
			fmt.Fprintf(&b, "if !%s(a.%s,b.%s) { return false }\n", g.equal(f.Type()), f.Name(), f.Name())
		}
		b.WriteString("return true\n")
	default:
		panic("unreviewed Docker type: " + g.typeName(t))
	}
	b.WriteString("}\n")
	g.body.WriteString(b.String())
	return name
}

func (g *generator) shape(s *types.Struct) string {
	var b strings.Builder
	b.WriteString("struct {\n")
	for i := 0; i < s.NumFields(); i++ {
		f := s.Field(i)
		fmt.Fprintf(&b, "// %s mirrors Docker's field for schema checking.\n", f.Name())
		if !f.Embedded() {
			fmt.Fprintf(&b, "%s ", f.Name())
		}
		b.WriteString(g.typeName(f.Type()))
		if tag := s.Tag(i); tag != "" {
			fmt.Fprintf(&b, " %q", tag)
		}
		b.WriteByte('\n')
	}
	b.WriteString("}")
	return b.String()
}
